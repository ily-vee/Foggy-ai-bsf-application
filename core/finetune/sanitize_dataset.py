import json
import re
from pathlib import Path

# Since this script sits in core/finetune/, current_dir is core/finetune/
CURRENT_DIR = Path(__file__).resolve().parent
DATASET_FILE = CURRENT_DIR / "dataset_llm.jsonl"
OUTPUT_FILE = CURRENT_DIR / "dataset_llm_sanitized.jsonl"

# Regex to match the boilerplate disclaimer and repetitive artifacts
DISCLAIMER_REGEX = re.compile(
    r'\s*[\d_.\-*]*\s*\(?_?This message was generated by a sophisticated AI.*?\)?_?',
    re.IGNORECASE | re.DOTALL
)

def sanitize_text(text: str) -> str:
    if not isinstance(text, str):
        return text
    # Direct substring target
    target_phrase = "This message was generated by a sophisticated AI"
    if target_phrase.lower() in text.lower():
        # Truncate everything starting from the disclaimer
        idx = text.lower().find(target_phrase.lower())
        # Walk back to remove leading numbering like '4. _' or newline
        cleaned = text[:idx].rstrip(" \n\r\t._-*0123456789(")
        return cleaned.strip()
    return text

def main():
    if not DATASET_FILE.exists():
        print(f"❌ Error: Dataset file '{DATASET_FILE}' not found.")
        return

    print(f"🧹 Starting Dataset Sanitization on '{DATASET_FILE.name}'...")
    
    cleaned_count = 0
    total_count = 0
    records = []

    with open(DATASET_FILE, "r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                records.append(json.loads(line))

    for item in records:
        total_count += 1
        # Handle ChatML / OpenAI message formats
        if "messages" in item:
            for msg in item["messages"]:
                if msg.get("role") == "assistant":
                    original = msg["content"]
                    cleaned = sanitize_text(original)
                    if original != cleaned:
                        cleaned_count += 1
                        msg["content"] = cleaned
        # Handle instruction-output formats
        elif "output" in item:
            original = item["output"]
            cleaned = sanitize_text(original)
            if original != cleaned:
                cleaned_count += 1
                item["output"] = cleaned

    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    print(f"✅ Sanitization complete!")
    print(f"📊 Cleaned {cleaned_count}/{total_count} records containing artifacts.")
    print(f"💾 Saved sanitized dataset to: {OUTPUT_FILE}")

if __name__ == "__main__":
    main()